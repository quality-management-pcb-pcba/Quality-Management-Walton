function parseDate(rawDate, rawMonth) {
  // Can be "18.05.2026", "15-Jun-2026", "4-Jul-2026", "10-Aug-2026", "30-Sep-2026"
  if (rawDate.includes('.')) {
    const [dd, mm, yyyy] = rawDate.split('.');
    return `${yyyy}-${mm.padStart(2, '0')}-${dd.padStart(2, '0')}`;
  }
  if (rawDate.includes('-')) {
    const [dd, mon, yyyy] = rawDate.split('-');
    const monthMap = {
      jan: '01', feb: '02', mar: '03', apr: '04', may: '05', jun: '06',
      jul: '07', aug: '08', sep: '09', oct: '10', nov: '11', dec: '12'
    };
    const m = monthMap[mon.toLowerCase()] || '06';
    return `${yyyy}-${m}-${dd.padStart(2, '0')}`;
  }
  return '2026-06-01';
}

